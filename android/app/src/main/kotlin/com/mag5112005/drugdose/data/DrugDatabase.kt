        return getDrugList().find { it.id == id }
    }

    fun searchDrugs(query: String): List<DrugData> {
        return getDrugList().filter {
            it.name.contains(query, ignoreCase = true) ||
                    it.category.contains(query, ignoreCase = true)
        }
    }

    fun getDrugsByCategory(category: String): List<DrugData> {
        return getDrugList().filter {
            it.category.contains(category, ignoreCase = true)
        }
    }
